export const getThemeTokens = (accentColor?: string): CvThemeTokens => {
  const key = (accentColor || "slate") as ThemeId;
  if (CV_THEMES[key]) {
    return CV_THEMES[key];
  }
  // Eğer özel hex kod girilmişse (#2563eb vs)
  if (accentColor && accentColor.startsWith("#")) {
    return {
      id: accentColor,
      name: "Özel Renk",
      desc: "Özel hex vurgu rengi",
      swatchHex: accentColor,
      headerBorder: "border-slate-800",
      nameText: "text-slate-950",
      titleText: "text-slate-900",
      sectionHeaderBar: "border-l-[3px] border-l-slate-900",
      sectionHeaderText: "text-slate-950",
      sectionHeaderBorder: "border-b border-slate-300",
      sectionHeaderBg: "bg-slate-50",
      companyText: "text-slate-900",
      dateBadge: "text-slate-700 bg-slate-50 border border-slate-200",
      techText: "text-slate-700",
      linkText: "text-blue-700 hover:text-blue-900",
      bulletMarker: "marker:text-slate-800",
      cardBorder: "border-slate-200",
      cardBg: "bg-slate-50",
      page2BarBorder: "border-slate-200",
      customHex: accentColor,
    };
  }
  return CV_THEMES.slate;
};

